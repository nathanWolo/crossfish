template <typename Board>
static int d16_mini_board_constraint(const Board &b) {
    if (b.n_moves == 0 || b.prev_move_was_pass) return 9;
    int sent = b.move_history.top().square;
    int oop = b.mini_board_states[0] | b.mini_board_states[1] | b.mini_board_states[2];
    if ((oop & (1 << sent)) != 0) return 9;
    return sent;
}

static int d16_mini_cjk_decode(
    const char *s, unsigned char *out, int out_max) {
    int n = 0;
    int bits = 0;
    uint32_t acc = 0;
    for (const unsigned char *p = (const unsigned char *)s; *p; p++) {
        if ((*p & 0xF0) != 0xE0) continue;
        uint32_t code = ((p[0] & 15u) << 12) | ((p[1] & 63u) << 6)
                      | (p[2] & 63u);
        p += 2;
        // U15 alphabet (tools/nnue_cjk14.py): U+3400..U+9FFF, then U+E000..U+F3FF.
        acc = (acc << 15) | (code >= 0xE000u ? code - 0xE000u + 27648u : code - 0x3400u);
        bits += 15;
        while (bits >= 8) {
            if (n >= out_max) return -1;
            bits -= 8;
            out[n++] = (unsigned char)(acc >> bits);
        }
    }
    return n;
}

static constexpr int D16_MN_N = 19683;
static constexpr int D16_MN_K = 256;
static constexpr int D16_MN_D = 16;
static constexpr int D16_MN_H = 8;
static constexpr int D16_MN_IN = 160;
static uint8_t D16_MN_CODE[D16_MN_N];
static float D16_MN_CENT[D16_MN_K * D16_MN_D];
static float D16_MN_SUPER[4 * D16_MN_D];
static float D16_MN_LOC[9 * D16_MN_D];
static float D16_MN_CONSTR[10 * D16_MN_D];
static float D16_MN_ACTIVE[2 * D16_MN_D];
static float D16_MN_W1[D16_MN_H * D16_MN_IN];
static float D16_MN_B1[D16_MN_H];
static float D16_MN_W2[D16_MN_H];
static float D16_MN_B2 = 0;
static bool D16_MN_READY = false;
static uint8_t D16_MN_MASK_CODE[1 << 18];
alignas(64) static float D16_MN_FAST_BASE[D16_MN_H];
alignas(64) static float D16_MN_FAST_CONSTR[10][D16_MN_H];
// [miniboard][centroid][super-class * 2 + active][hidden neuron]
alignas(64) static float D16_MN_FAST_MB[9][D16_MN_K][8][D16_MN_H];
static constexpr int D16_MN_FACTOR_SCALE = 192;
// Common live/inactive projection: 9*256*8*4 = 72 KiB.
alignas(64) static int32_t D16_MN_FACTOR_CODE[9][D16_MN_K][D16_MN_H];
alignas(64) static int32_t D16_MN_FACTOR_INIT[10][D16_MN_H];
alignas(64) static int32_t D16_MN_FACTOR_SUPER[9][4][D16_MN_H];
alignas(64) static int32_t D16_MN_FACTOR_ACTIVE[9][D16_MN_H];

static int d16_mini_mask_index(int mine, int opp) {
    int idx = 0;
    idx += (mine & 1) ? 1 : ((opp & 1) ? 2 : 0);
    idx += (mine & 2) ? 3 : ((opp & 2) ? 6 : 0);
    idx += (mine & 4) ? 9 : ((opp & 4) ? 18 : 0);
    idx += (mine & 8) ? 27 : ((opp & 8) ? 54 : 0);
    idx += (mine & 16) ? 81 : ((opp & 16) ? 162 : 0);
    idx += (mine & 32) ? 243 : ((opp & 32) ? 486 : 0);
    idx += (mine & 64) ? 729 : ((opp & 64) ? 1458 : 0);
    idx += (mine & 128) ? 2187 : ((opp & 128) ? 4374 : 0);
    idx += (mine & 256) ? 6561 : ((opp & 256) ? 13122 : 0);
    return idx;
}

static void d16_mini_build_fast_tables() {
    for (int mine = 0; mine < 512; mine++) {
        for (int opp = 0; opp < 512; opp++) {
            int packed = (mine << 9) | opp;
            D16_MN_MASK_CODE[packed] = (mine & opp)
                ? 0
                : D16_MN_CODE[d16_mini_mask_index(mine, opp)];
        }
    }

    for (int h = 0; h < D16_MN_H; h++) {
        float base = D16_MN_B1[h];
        const float *row = D16_MN_W1 + h * D16_MN_IN;
        for (int mb = 0; mb < 9; mb++) {
            for (int d = 0; d < D16_MN_D; d++) {
                base += row[mb * D16_MN_D + d] * D16_MN_LOC[mb * D16_MN_D + d];
            }
        }
        D16_MN_FAST_BASE[h] = base;
        for (int c = 0; c < 10; c++) {
            float v = 0;
            for (int d = 0; d < D16_MN_D; d++) {
                v += row[9 * D16_MN_D + d] * D16_MN_CONSTR[c * D16_MN_D + d];
            }
            D16_MN_FAST_CONSTR[c][h] = v;
        }
    }

    for (int mb = 0; mb < 9; mb++) {
        for (int code = 0; code < D16_MN_K; code++) {
            for (int super_cls = 0; super_cls < 4; super_cls++) {
                for (int active = 0; active < 2; active++) {
                    int variant = super_cls * 2 + active;
                    for (int h = 0; h < D16_MN_H; h++) {
                        const float *row = D16_MN_W1 + h * D16_MN_IN + mb * D16_MN_D;
                        float v = 0;
                        for (int d = 0; d < D16_MN_D; d++) {
                            float x = D16_MN_CENT[code * D16_MN_D + d]
                                    + D16_MN_SUPER[super_cls * D16_MN_D + d]
                                    + D16_MN_ACTIVE[active * D16_MN_D + d];
                            v += row[d] * x;
                        }
                        D16_MN_FAST_MB[mb][code][variant][h] = v;
                    }
                }
            }
        }
    }

    for (int c = 0; c < 10; c++) {
        for (int h = 0; h < D16_MN_H; h++) {
            D16_MN_FACTOR_INIT[c][h] = (int32_t)std::lround(
                (D16_MN_FAST_BASE[h] + D16_MN_FAST_CONSTR[c][h])
                * D16_MN_FACTOR_SCALE);
        }
    }
    for (int mb = 0; mb < 9; mb++) {
        for (int code = 0; code < D16_MN_K; code++) {
            for (int h = 0; h < D16_MN_H; h++) {
                D16_MN_FACTOR_CODE[mb][code][h] =
                    (int32_t)std::lround(
                        D16_MN_FAST_MB[mb][code][0][h]
                        * D16_MN_FACTOR_SCALE);
            }
        }
        for (int super_cls = 0; super_cls < 4; super_cls++) {
            for (int h = 0; h < D16_MN_H; h++) {
                D16_MN_FACTOR_SUPER[mb][super_cls][h] =
                    (int32_t)std::lround(
                        (D16_MN_FAST_MB[mb][0][super_cls * 2][h]
                         - D16_MN_FAST_MB[mb][0][0][h])
                        * D16_MN_FACTOR_SCALE);
            }
        }
        for (int h = 0; h < D16_MN_H; h++) {
            D16_MN_FACTOR_ACTIVE[mb][h] =
                (int32_t)std::lround(
                    (D16_MN_FAST_MB[mb][0][1][h]
                     - D16_MN_FAST_MB[mb][0][0][h])
                    * D16_MN_FACTOR_SCALE);
        }
    }
}

static bool d16_mini_load_packed() {
    if (D16_MN_READY) return true;
    static unsigned char buf[65536];
    int nb = d16_mini_cjk_decode(D16_MINI_PACK_CJK, buf, (int)sizeof(buf));
    const int need = D16_MN_N + D16_MN_K * D16_MN_D * 4 + (4 + 9 + 10 + 2) * D16_MN_D * 4
                     + D16_MN_H * D16_MN_IN * 4 + D16_MN_H * 4 + D16_MN_H * 4 + 4;
    if (nb < need) return false;
    int off = 0;
    memcpy(D16_MN_CODE, buf + off, D16_MN_N); off += D16_MN_N;
    memcpy(D16_MN_CENT, buf + off, D16_MN_K * D16_MN_D * 4); off += D16_MN_K * D16_MN_D * 4;
    memcpy(D16_MN_SUPER, buf + off, 4 * D16_MN_D * 4); off += 4 * D16_MN_D * 4;
    memcpy(D16_MN_LOC, buf + off, 9 * D16_MN_D * 4); off += 9 * D16_MN_D * 4;
    memcpy(D16_MN_CONSTR, buf + off, 10 * D16_MN_D * 4); off += 10 * D16_MN_D * 4;
    memcpy(D16_MN_ACTIVE, buf + off, 2 * D16_MN_D * 4); off += 2 * D16_MN_D * 4;
    memcpy(D16_MN_W1, buf + off, D16_MN_H * D16_MN_IN * 4); off += D16_MN_H * D16_MN_IN * 4;
    memcpy(D16_MN_B1, buf + off, D16_MN_H * 4); off += D16_MN_H * 4;
    memcpy(D16_MN_W2, buf + off, D16_MN_H * 4); off += D16_MN_H * 4;
    memcpy(&D16_MN_B2, buf + off, 4);
    d16_mini_build_fast_tables();
    D16_MN_READY = true;
    return true;
}

static int d16_evaluate_mini(const GlobalBoard &b) {
    if (!D16_MN_READY && !d16_mini_load_packed()) return 0;
    const int stm = b.n_moves & 1;
    const int c = d16_mini_board_constraint(b);
    float x[D16_MN_IN];
    for (int mb = 0; mb < 9; mb++) {
        const int mine = b.mini_boards[mb].markers[stm];
        const int opp = b.mini_boards[mb].markers[stm ^ 1];
        int idx = 0;
        idx += (mine & 1) ? 1 : ((opp & 1) ? 2 : 0);
        idx += (mine & 2) ? 3 : ((opp & 2) ? 6 : 0);
        idx += (mine & 4) ? 9 : ((opp & 4) ? 18 : 0);
        idx += (mine & 8) ? 27 : ((opp & 8) ? 54 : 0);
        idx += (mine & 16) ? 81 : ((opp & 16) ? 162 : 0);
        idx += (mine & 32) ? 243 : ((opp & 32) ? 486 : 0);
        idx += (mine & 64) ? 729 : ((opp & 64) ? 1458 : 0);
        idx += (mine & 128) ? 2187 : ((opp & 128) ? 4374 : 0);
        idx += (mine & 256) ? 6561 : ((opp & 256) ? 13122 : 0);
        int super_cls = 0;
        if (b.mini_board_states[stm] & (1 << mb)) super_cls = 1;
        else if (b.mini_board_states[stm ^ 1] & (1 << mb)) super_cls = 2;
        else if (b.mini_board_states[2] & (1 << mb)) super_cls = 3;
        const int act = (c == mb) ? 1 : 0;
        const float *e = D16_MN_CENT + (int)D16_MN_CODE[idx] * D16_MN_D;
        const float *s = D16_MN_SUPER + super_cls * D16_MN_D;
        const float *l = D16_MN_LOC + mb * D16_MN_D;
        const float *a = D16_MN_ACTIVE + act * D16_MN_D;
        float *dst = x + mb * D16_MN_D;
        for (int i = 0; i < D16_MN_D; i++) dst[i] = e[i] + s[i] + l[i] + a[i];
    }
    const float *ce = D16_MN_CONSTR + c * D16_MN_D;
    for (int i = 0; i < D16_MN_D; i++) x[9 * D16_MN_D + i] = ce[i];
    float out = D16_MN_B2;
    for (int j = 0; j < D16_MN_H; j++) {
        const float *row = D16_MN_W1 + j * D16_MN_IN;
        float s = D16_MN_B1[j];
        for (int i = 0; i < D16_MN_IN; i++) s += row[i] * x[i];
        if (s > 0) out += D16_MN_W2[j] * s;
    }
    return (int)std::lround(out);
}

// AVX2 MiniNet. Same network as d16_evaluate_mini; mul+add (not FMA) to match
// the codingame AVX2-only target. Horizontal-add order can differ by 1
// from the scalar path after lround.
__attribute__((always_inline)) static inline float d16_mini_hsum256(__m256 v) {
    __m128 lo = _mm256_castps256_ps128(v);
    __m128 hi = _mm256_extractf128_ps(v, 1);
    __m128 s = _mm_add_ps(lo, hi);
    s = _mm_add_ps(s, _mm_movehl_ps(s, s));
    s = _mm_add_ss(s, _mm_shuffle_ps(s, s, 1));
    return _mm_cvtss_f32(s);
}

static int d16_evaluate_mini_avx(const GlobalBoard &b) {
    return d16_evaluate_mini(b);
}

// First-layer projections are constant for each local centroid, miniboard,
// super-board class, and active-board flag. Summing those four-neuron
// projections avoids rebuilding 80 features and running 40 vector products
// at every qsearch leaf.
template <typename Board>
static int d16_evaluate_mini_fast(const Board &b) {
    if (!D16_MN_READY && !d16_mini_load_packed()) return 0;
    const int stm = b.n_moves & 1;
    const int c = d16_mini_board_constraint(b);
    __m256i hidden = _mm256_load_si256(
        (const __m256i *)D16_MN_FACTOR_INIT[c]);
    for (int mb = 0; mb < 9; mb++) {
        const int mine = b.mini_boards[mb].markers[stm];
        const int opp = b.mini_boards[mb].markers[stm ^ 1];
        const int code = D16_MN_MASK_CODE[(mine << 9) | opp];
        hidden = _mm256_add_epi32(
            hidden,
            _mm256_load_si256(
                (const __m256i *)D16_MN_FACTOR_CODE[mb][code]));
        const int bit = 1 << mb;
        int super_cls = 0;
        if (b.mini_board_states[stm] & bit) super_cls = 1;
        else if (b.mini_board_states[stm ^ 1] & bit) super_cls = 2;
        else if (b.mini_board_states[2] & bit) super_cls = 3;
        if (super_cls) {
            hidden = _mm256_add_epi32(
                hidden,
                _mm256_load_si256(
                    (const __m256i *)D16_MN_FACTOR_SUPER[mb][super_cls]));
        }
    }
    if (c < 9) {
        hidden = _mm256_add_epi32(
            hidden,
            _mm256_load_si256(
                (const __m256i *)D16_MN_FACTOR_ACTIVE[c]));
    }
    __m256 value = _mm256_cvtepi32_ps(hidden);
    value = _mm256_max_ps(value, _mm256_setzero_ps());
    value = _mm256_mul_ps(value, _mm256_loadu_ps(D16_MN_W2));
    const float out =
        D16_MN_B2 + d16_mini_hsum256(value) / D16_MN_FACTOR_SCALE;
    return (int)std::lround(out);
}
